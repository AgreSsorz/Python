""" 
Подключаем встроенный модуль os из стандартной библиотеки Python,
который даёт доступ к файловой системе.
"""
import os

""" Отрисовываем tui меню """
def main_menu():
    while True:
        print("""
+=====     Скрипт удаления текста v1.0      =====+
|                                                |
|  1. Удалить лишний текст из названия файла     |
|  2. О программе                                |
|  3. Выход                                      |
+================================================+

    """)
    
        """ Обрабатываем ввод и переходим в подменю. """
        choice = input("Выберите пункт: ")
        
        if choice == '1':
            remove_text_submenu()
            
        elif choice == '2':
            about_submenu()
            
        elif choice == '3':
            print("\nДо свидания!")
            break
        else:
            print("\nНеверный выбор!")
            input("Нажмите Enter...")

def remove_text_submenu():
    while True:
        print("""
+=====     Скрипт удаления текста v1.0      =====+
|                                                |
|  > Удалить лишний текст из названия файла <    |
+================================================+
    """)
        break
    
    """ Запрашиваем исходные данные """
    my_folder = input("Путь до папки: ")
    text_to_delete = input("Текст, который нужно удалить: ")
    
    """ Получаем список всех файлов и папок """
    files = os.listdir(my_folder)
    
    """ Перебор списка """
    for filename in files:
        """ Проверяем, есть ли название сайта в имени файла """
        if text_to_delete in filename:
            """ Убираем ненужный текст, который выбрали """
            new_filename = filename.replace(text_to_delete, "") \
                .replace(" .", ".").strip()

            
            """ Собираем полные пути к старому и новому файлу """
            old_path = os.path.join(my_folder, filename)
            new_path = os.path.join(my_folder, new_filename)
            
            """ Переименовываем сам файл """
            os.rename(old_path, new_path)
            print(f"Готово: {filename} -> {new_filename}")

def about_submenu():
    print("""
+=====     Скрипт удаления текста v1.0      =====+
|                                                |
|  > О программе                              <  |
|  Данный скрипт позволяет удалить               |
|  ненужный текст или ссылки из имени файла      |
|  по указанному пути.                           |
|                                                |
|  Автор: Agre_Ssor                              |
|  Год: 2026                                     |
|                                                |
|  q. Назад                                      |
+================================================+
    """)

    while True:
        key = input(": ")
        """ Проверяем, нажата ли нужная клавиша и возвращаемся в main_menu. """
        if key.lower() in ['q', 'й']:
            return

""" Возврат в главное меню """
main_menu()
